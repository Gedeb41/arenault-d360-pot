#!/usr/bin/env python3
"""Export the Product__dlm catalogue of a Data Cloud org to data/products.js.

Usage: python3 tools/export_products.py [--org data360-demo]
Requires the sf CLI authenticated on the org.
"""
import argparse
import html
import json
import os
import subprocess
import tempfile
from pathlib import Path

import accessory_images

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "products.js"

IMG = "https://s3.amazonaws.com/northerntrailoutfitters.com/quadstar/default/images/large/"

# Exact visuals for the flagship models (local images when the site has them)
IMAGE_BY_ID = {
    "1": "images/ePhone12-blackf.png",
    "2": "images/ePhone12-Mini-pink.png",
    "3": "images/ePhone12-Pro-blackf.png",
    "4": IMG + "Simpson-Galaxy10-blackf.jpg",
    "5": IMG + "Simpson-Galaxy10X-blackf.jpg",
    "6": "images/ePad5-Mini-blackf.png",
    "7": IMG + "ePad5-Pro-blackf.jpg",
    "8": IMG + "Simpson-Tab-Mini-blackf.jpg",
    "9": IMG + "Simpson-Tab-Max-blackf.jpg",
    "16": "images/ePhone14-Edge.png",
}

# Fallback pools, picked deterministically by product id
IMAGE_POOLS = {
    ("ePhone", "Phone"): [IMG + n for n in (
        "ePhone12-blackf.jpg", "ePhone12-Pro-blackf.jpg", "ePhone12-Mini-pink.jpg",
        "ePhone12-Pro-silver.jpg", "ePhone12-Pro-neon.jpg", "ePhone12-Mini-neon.jpg",
        "ePhone12-Mini-blackf.jpg")],
    ("*", "Phone"): [IMG + "Simpson-Galaxy10-blackf.jpg", IMG + "Simpson-Galaxy10X-blackf.jpg"],
    ("ePhone", "Tablet"): [IMG + n for n in (
        "ePad5-Mini-blackf.jpg", "ePad5-Pro-blackf.jpg", "ePad5-Pro-silverf.jpg", "ePad5-Mini-silverf.jpg")],
    ("ePad", "Tablet"): [IMG + "ePad5-Pro-silverf.jpg"],
    ("*", "Tablet"): [IMG + "Simpson-Tab-Mini-blackf.jpg", IMG + "Simpson-Tab-Max-blackf.jpg"],
}

SQL = ("SELECT ID__c, Product_Name__c, Brand__c, Product_Type__c, Color__c, Price__c, "
       "Product_Description__c FROM Product__dlm")


def query(org):
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump({"sql": SQL}, f)
        body = f.name
    try:
        proc = subprocess.run(
            ["sf", "api", "request", "rest", "/services/data/v62.0/ssot/queryv2",
             "--method", "POST", "--body", "@" + body, "-o", org],
            capture_output=True, text=True)
    finally:
        os.unlink(body)
    if proc.returncode:
        raise SystemExit(f"sf CLI failed ({proc.returncode}):\n{proc.stderr}")
    res = json.loads(proc.stdout)
    cols = sorted(res["metadata"], key=lambda c: res["metadata"][c]["placeInOrder"])
    return [dict(zip(cols, row)) for row in res["data"]]


def image_for(pid, brand, ptype):
    if pid in IMAGE_BY_ID:
        return IMAGE_BY_ID[pid]
    pool = IMAGE_POOLS.get((brand, ptype)) or IMAGE_POOLS.get(("*", ptype)) or ["images/accessory.svg"]
    return pool[int(pid) % len(pool)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--org", default="data360-demo")
    args = ap.parse_args()

    products = []
    for r in query(args.org):
        text = {k: html.unescape(v) if isinstance(v, str) else v for k, v in r.items()}
        pid = text["ID__c"]
        colors = [c.strip() for c in (text["Color__c"] or "").split(",") if c.strip()]
        product = {
            "id": pid,
            "name": text["Product_Name__c"],
            "brand": text["Brand__c"],
            "type": text["Product_Type__c"],
            "colors": colors,
            "price": float((text["Price__c"] or "0").replace(",", "")),
            "description": text["Product_Description__c"] or "",
            "image": image_for(pid, text["Brand__c"], text["Product_Type__c"]),
        }
        # Accessories: generated illustration per colour, swapped by the colour picker
        kind = accessory_images.kind_of(product["name"])
        if product["type"] == "Accessories" and kind:
            product["images"] = {c: accessory_images.write(ROOT, kind, c) for c in colors or ["White"]}
            product["image"] = next(iter(product["images"].values()))
        products.append(product)
    products.sort(key=lambda p: int(p["id"]))

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/export_products.py from Product__dlm — do not edit by hand\n"
        "window.QUADSTAR_PRODUCTS = " + json.dumps(products, indent=1, ensure_ascii=False) + ";\n")
    print(f"{len(products)} products -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
